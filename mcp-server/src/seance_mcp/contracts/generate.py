"""Generate docs/contracts/{schemas,examples}. Deterministic: re-running changes nothing.

    python -m seance_mcp.contracts.generate            # write into docs/contracts
    python -m seance_mcp.contracts.generate --check    # fail if committed files differ
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from ..fake import fake_insurance
from . import examples
from .check import CONTRACTS, validate_all
from .models import SCHEMAS
from .record import SCENARIOS, record

README = """\
# Contract examples

Generated by `python -m seance_mcp.contracts.generate` (integrator). Do not edit by hand;
change `seance_mcp/contracts/` and regenerate. Normative text: `docs/contracts.md`.

| Path | What |
|---|---|
| `../schemas/*.schema.json` | JSON Schema 2020-12, generated from the Pydantic models |
| `events/<type>.json` | one server event of each type (a full envelope) |
| `events/client-<type>.json` | one client message of each type |
| `transcripts/*.jsonl` | whole conversations, recorded by driving the real service, gate, audit log and fake app |
| `rest/*.json` | REST bodies (`/api/health`, `/api/session`, `/api/apps`, `/api/audit`) |
| `spirit-map/spirit-map-view.json` | `GET /api/apps/{id}/spirit-map` |
| `toolpack/tools.json`, `tool-approvals.json`, `key-policy.golden.json` | tool pack (real `def_hash`), approvals, golden policy |
| `capture/capture.json` | a `gss.capture/1` file that `FakeApp.from_capture` loads |

## Transcript format
One JSON object per line:

- `{"dir":"server","delay_ms":150,"event":{...envelope...}}` a server event, emitted `delay_ms` after the previous line.
- `{"dir":"client","msg":{...}}` a client message. A replayer (UI mock mode) waits for the user
  to do the same kind of action (`connect_system`, `user_message`, `confirm_decision`) before
  playing the following server lines; the first `hello` is played immediately.

The transcripts: `lookup`, `commit-approve`, `commit-deny`, `commit-expire`, `injection`
(hostile text in the screen data), `session-lost` (ends with a reconnect), `ambiguous-ack` (a key goes out, the host never answers: nothing resent, session closed, reconnect), `read-only`
(`SEANCE_ALLOW_COMMIT=0`: approval ends `blocked_read_only`).

## Use
- Agent D: your emitted events must validate against `schemas/server-event.schema.json`; replay these
  transcripts through your models; `check_stream` (in `seance_mcp/contracts/check.py`) shows the
  ordering rules.
- Agent C: your guards and reducer must accept every file here; mock mode plays the transcripts.
- Agent B: `toolpack/` and `spirit-map/` are the formats you produce; `key-policy.golden.json` is the
  policy your approved policy must equal for `fake-insurance` (modulo screen_id).
"""


def _dumps(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def build() -> dict[str, str]:
    """relative path (under docs/contracts) -> file text."""
    files: dict[str, str] = {}
    for name, adapter in SCHEMAS.items():
        schema = adapter.json_schema()
        schema = {"$schema": "https://json-schema.org/draft/2020-12/schema", **schema}
        files[f"schemas/{name}.schema.json"] = _dumps(schema)

    first_server: dict[str, dict[str, Any]] = {}
    first_client: dict[str, dict[str, Any]] = {}
    audit_entries: list[dict[str, Any]] = []
    for name in SCENARIOS:
        lines, service = record(name)
        files[f"examples/transcripts/{name}.jsonl"] = "".join(
            json.dumps(line, ensure_ascii=False, separators=(",", ":")) + "\n" for line in lines)
        for line in lines:
            if line["dir"] == "server":
                first_server.setdefault(line["event"]["type"], line["event"])
            else:
                first_client.setdefault(line["msg"]["type"], line["msg"])
        if name == "commit-approve":
            audit_entries = [e.model_dump(mode="json") for e in service.audit.read()]
            assert service.audit.verify() is None

    first_server.setdefault("pong", {"v": 1, "type": "pong", "seq": 1, "ts": "2026-11-24T10:00:00.000Z",
                                      "session_id": "s_01", "turn_id": None, "data": {}})
    first_server.setdefault("error", {"v": 1, "type": "error", "seq": 1, "ts": "2026-11-24T10:00:00.000Z",
                                       "session_id": "s_01", "turn_id": None,
                                       "data": {"code": "observer_only", "message": "This connection only observes.",
                                                "recoverable": True, "ref": "u_09"}})
    first_client.setdefault("cancel_turn", {"id": "u_10", "type": "cancel_turn", "turn_id": "t_01"})
    first_client.setdefault("ping", {"id": "u_11", "type": "ping"})
    for t, ev in sorted(first_server.items()):
        files[f"examples/events/{t}.json"] = _dumps(ev)
    for t, msg in sorted(first_client.items()):
        files[f"examples/events/client-{t}.json"] = _dumps(msg)

    app = fake_insurance()
    for rel, obj in examples.rest_examples(audit_entries).items():
        files[f"examples/{rel}"] = _dumps(obj)
    files["examples/spirit-map/spirit-map-view.json"] = _dumps(examples.spirit_map_view(app))
    files["examples/toolpack/tools.json"] = _dumps(examples.toolpack(app))
    files["examples/toolpack/tool-approvals.json"] = _dumps(examples.approvals(app))
    files["examples/toolpack/key-policy.golden.json"] = _dumps(examples.key_policy(app))
    files["examples/capture/capture.json"] = _dumps(examples.capture(app))
    files["examples/README.md"] = README
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if committed files differ from a fresh build")
    ap.add_argument("--root", type=Path, default=CONTRACTS)
    args = ap.parse_args()
    files = build()
    if args.check:
        bad = [rel for rel, text in files.items()
               if not (args.root / rel).exists() or (args.root / rel).read_text(encoding="utf-8").replace("\r\n", "\n") != text]
        if bad:
            print("contract files out of date (run python -m seance_mcp.contracts.generate):\n  " + "\n  ".join(bad),
                  file=sys.stderr)
            return 1
        print(f"ok: {len(files)} files match")
        return 0
    for rel, text in files.items():
        p = args.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} files under {args.root}")
    if args.root == CONTRACTS:
        for line in validate_all():
            print(line)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
