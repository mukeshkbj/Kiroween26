"""Pydantic models for docs/contracts.md (v1): the source of the committed JSON Schemas.

These describe the wire formats between components (websocket events, client
messages, REST bodies, tool pack, key policy, SpiritMapView, captures). They are
deliberately permissive about unknown fields (consumers ignore them, contracts
section 4) and strict about the fields a consumer relies on.

Owner: integrator. Agents D and C validate their own implementations against the
generated schemas and the committed examples; they do not edit this file.
"""
